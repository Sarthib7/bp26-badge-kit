'use strict';

// meet-board example server tests. Requests are signed exactly the way the
// badge server signs them (badge-http-v1, Ed25519), with a throwaway key made
// in memory for the test run; nothing is written to disk.

const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const http = require('node:http');
const net = require('node:net');
const srv = require('../server/meet-board/server.js');

const APP = 'mesh-demo';
const ORIGIN = 'https://scores.example.com';

function testKey() {
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
  const raw = publicKey.export({ format: 'der', type: 'spki' }).subarray(-32);
  return { id: crypto.createHash('sha256').update(raw).digest('hex').slice(0, 16), raw, pub: publicKey, priv: privateKey };
}

function sign({ method = 'POST', url = `${ORIGIN}/report`, body, app = APP, badge = 'AA1111', user = 'user-1',
  time = Date.now(), reqId = crypto.randomBytes(8).toString('hex'), key }) {
  const hash = crypto.createHash('sha256').update(body).digest('hex');
  const signed = ['badge-http-v1', method, url, hash, app, badge, user, String(time), reqId].join('\n');
  const sig = crypto.sign(null, Buffer.from(signed), key.priv);
  return {
    reqId,
    headers: {
      'x-badge-app': app, 'x-badge-id': badge, 'x-badge-user': user, 'x-badge-time': String(time),
      'x-badge-request': reqId, 'x-badge-key': key.id, 'x-badge-signature': sig.toString('base64'),
      'content-type': 'application/json',
    },
  };
}

async function start(opts) {
  const server = srv.createServer(APP, { publicOrigin: ORIGIN, keyUrl: null, ...opts });
  await new Promise((res) => server.listen(0, '127.0.0.1', res));
  return { server, base: `http://127.0.0.1:${server.address().port}` };
}

describe('meet-board example server', () => {
  const key = testKey();
  let base, server;
  before(async () => { ({ server, base } = await start({ trustedKeys: [{ id: key.id, key: key.pub }] })); });
  after(async () => { await new Promise((res) => server.close(res)); });

  async function post(body, signOpts = {}, mutate) {
    const s = sign({ body, key, ...signOpts });
    if (mutate) mutate(s.headers);
    const r = await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body });
    let j = null;
    try { j = await r.json(); } catch { /* non-json */ }
    return { status: r.status, json: j, reqId: s.reqId };
  }

  it('accepts a valid signed score', async () => {
    const r = await post(JSON.stringify({ score: 120 }));
    assert.equal(r.status, 200);
    assert.equal(r.json.best, 120);
  });

  it('hashes raw bytes (multibyte bodies verify)', async () => {
    const r = await post(JSON.stringify({ score: 7, note: 'é€😀'.repeat(200) }), { user: 'utf8-user' });
    assert.equal(r.status, 200);
  });

  it('rejects a tampered body (signature over different bytes)', async () => {
    const body = JSON.stringify({ score: 11 });
    const s = sign({ body, key });
    const r = await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body: JSON.stringify({ score: 99999 }) });
    assert.equal(r.status, 403);
  });

  it('rejects signature bypass attempts', async () => {
    const body = JSON.stringify({ score: 5 });
    const cases = [
      (h) => { h['x-badge-signature'] = ''; },
      (h) => { h['x-badge-signature'] = 'AAAA'; },
      (h) => { h['x-badge-signature'] = Buffer.alloc(64).toString('base64'); },
      (h) => { delete h['x-badge-signature']; },
      (h) => { h['x-badge-key'] = 'ffffffffffffffff'; },       // unknown key id
      (h) => { h['x-badge-app'] = 'other-app'; },               // app swap
      (h) => { h['x-badge-user'] = 'someone-else'; },           // identity swap
      (h) => { h['x-badge-time'] = 'NaN'; },
    ];
    for (const m of cases) {
      const r = await post(body, {}, m);
      assert.equal(r.status, 403, `case ${m}`);
    }
    // A key generated by the attacker is never trusted.
    const evil = testKey();
    const s = sign({ body, key: evil });
    const r = await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body });
    assert.equal(r.status, 403);
  });

  it('ignores X-Forwarded-Host when a public origin is configured', async () => {
    const body = JSON.stringify({ score: 9 });
    const s = sign({ body, key, url: 'https://attacker.example/report' });
    s.headers['x-forwarded-host'] = 'attacker.example';
    const r = await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body });
    assert.equal(r.status, 403);
  });

  it('rejects a replayed request id', async () => {
    const body = JSON.stringify({ score: 50 });
    const r1 = await post(body);
    assert.equal(r1.status, 200);
    const r2 = await post(body, { reqId: r1.reqId });
    assert.equal(r2.status, 403);
  });

  it('orders the board best-first and clamps n', async () => {
    await post(JSON.stringify({ score: 300 }));
    const rows = await (await fetch(`${base}/board?n=5`)).json();
    assert.ok(Array.isArray(rows) && rows.length >= 1);
    assert.ok(rows[0].best >= (rows[1] ? rows[1].best : -1));
    assert.equal(rows[0].user, 'user-1');
    const neg = await (await fetch(`${base}/board?n=-3`)).json();
    assert.ok(neg.length >= 1 && neg.length <= 50);
  });

  it('rejects timestamps outside the 60 s window', async () => {
    const body = JSON.stringify({ score: 5 });
    assert.equal((await post(body, { time: Date.now() + 61000 })).status, 403);
    assert.equal((await post(body, { time: Date.now() - 61000 })).status, 403);
  });

  it('rejects bad scores', async () => {
    for (const b of ['null', '"x"', '{"score":"1"}', '{"score":-1}', '{"score":1e999}', '{}', 'not json']) {
      const r = await post(b);
      assert.equal(r.status, 400, b);
    }
  });

  it('rejects oversized bodies with 413', async () => {
    const body = JSON.stringify({ score: 1, pad: 'x'.repeat(5000) });
    let status = 'thrown';
    try { status = (await post(body)).status; } catch { status = 'thrown'; }
    assert.ok(status === 413 || status === 'thrown', `oversize must not score, got ${status}`);
  });

  it('rejects nested JSON bombs and unknown routes', async () => {
    const deep = '['.repeat(1900) + ']'.repeat(1900);
    const r1 = await post(deep);
    assert.equal(r1.status, 400);
    const r2 = await fetch(`${base}/..%2f..%2fetc%2fpasswd`);
    assert.equal(r2.status, 404);
    const r3 = await fetch(`${base}/api/http/key`);
    assert.equal(r3.status, 404); // this server publishes no key of its own
  });

  it('sends no CORS headers and no key material', async () => {
    const r = await fetch(`${base}/board`, { headers: { origin: 'https://evil.example' } });
    assert.equal(r.headers.get('access-control-allow-origin'), null);
    const text = await r.text();
    assert.ok(!/PRIVATE KEY|BEGIN/.test(text));
  });

  it('survives a hostile Host header (no crash)', async () => {
    const port = server.address().port;
    const reply = await new Promise((resolve) => {
      const sock = net.connect(port, '127.0.0.1', () => {
        sock.write('GET /board HTTP/1.1\r\nHost: a b\r\nConnection: close\r\n\r\n');
      });
      let data = '';
      sock.on('data', (d) => { data += d; });
      sock.on('end', () => resolve(data));
      sock.on('error', () => resolve(data));
    });
    assert.ok(/^HTTP\/1\.1 (200|400)/.test(reply), reply.slice(0, 40));
    const after = await fetch(`${base}/board`);
    assert.equal(after.status, 200);
  });
});

describe('meet-board replay window and key rotation', () => {
  it('keeps a future-stamped request replay-protected for its whole life', async () => {
    const key = testKey();
    let now = 1790000000000;
    const { server, base } = await start({ trustedKeys: [{ id: key.id, key: key.pub }], now: () => now });
    try {
      const body = JSON.stringify({ score: 1 });
      const s = sign({ body, key, time: now + 59000 });
      assert.equal((await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body })).status, 200);
      now += 61000; // first-seen + 61 s, but the stamp is still inside the window
      assert.equal((await fetch(`${base}/report`, { method: 'POST', headers: s.headers, body })).status, 403);
    } finally { await new Promise((res) => server.close(res)); }
  });

  it('fetches an unknown key id from the key URL (rotation), at most once a minute', async () => {
    const key = testKey();
    let fetches = 0;
    const keySrv = http.createServer((req, res) => {
      fetches += 1;
      res.setHeader('content-type', 'application/json');
      res.end(JSON.stringify({ id: key.id, alg: 'Ed25519', key: key.raw.toString('base64') }));
    });
    await new Promise((res) => keySrv.listen(0, '127.0.0.1', res));
    const { server, base } = await start({ keyUrl: `http://127.0.0.1:${keySrv.address().port}/api/http/key` });
    try {
      const body = JSON.stringify({ score: 3 });
      const s1 = sign({ body, key });
      assert.equal((await fetch(`${base}/report`, { method: 'POST', headers: s1.headers, body })).status, 200);
      const evil = testKey();
      const s2 = sign({ body, key: evil });
      assert.equal((await fetch(`${base}/report`, { method: 'POST', headers: s2.headers, body })).status, 403);
      const s3 = sign({ body, key: evil });
      assert.equal((await fetch(`${base}/report`, { method: 'POST', headers: s3.headers, body })).status, 403);
      assert.equal(fetches, 1, 'unknown ids must not trigger a fetch storm');
    } finally {
      await new Promise((res) => server.close(res));
      await new Promise((res) => keySrv.close(res));
    }
  });

  it('rate-limits abusive clients (example 120/min)', async () => {
    const key = testKey();
    const { server, base } = await start({ trustedKeys: [{ id: key.id, key: key.pub }] });
    try {
      let last = 200;
      for (let i = 0; i < 130; i++) {
        last = (await fetch(`${base}/board`)).status;
        if (last === 429) break;
      }
      assert.equal(last, 429);
    } finally { await new Promise((res) => server.close(res)); }
  });

  it('never writes keys to disk or logs them', () => {
    const src = require('node:fs').readFileSync(require.resolve('../server/meet-board/server.js'), 'utf8');
    assert.ok(!/writeFile|createWriteStream|generateKeyPair/.test(src), 'server must not create or store keys');
    assert.ok(!/console\.(log|error)\([^)]*key/i.test(src), 'server must not log keys');
  });
});
